/**
 * rankings-proposed.mjs — PROPOSED re-authoring of the tuner fixture.
 *
 * STAGE 1 FINDING: the production fixture (assets/data/product-demo.js
 * RANKINGS, authored by tools/rankings.mjs) never reorders for the advertised
 * move. Sneha Iyer is first in all sixty-four combinations and twenty-eight of
 * them return the default order, so the control says "you decide what counts"
 * and the list disagrees.
 *
 * This file is the same authoring approach with two changes, both taken from
 * the product's own model rather than invented for the demo:
 *
 *   1. THE GATE IS REAL. A skill set to CRITICAL disqualifies every candidate
 *      who is MISSING it, at the retrieval layer, before scoring
 *      (CRITICAL_GATE, docs/phase-4.md § 1.1). The production fixture scores
 *      them anyway, which contradicts the page's own critical-gate composition.
 *      Here they carry no score, and the row says why.
 *
 *   2. A PARTIAL COUNTS FOR LESS THE HIGHER THE TIER. A transferable skill is
 *      a small risk on a bonus requirement and a large one on a critical
 *      requirement. The factor steps down with the tier, which is what makes
 *      the advertised move honest: "Kubernetes to critical" now promotes Rahul
 *      Verma, who has production Kubernetes, above Sneha, whose Kubernetes is
 *      Docker experience transferring.
 *
 * The default combination reproduces the six published scores EXACTLY
 * (87 · 81 · 78 · 74 · 68 · 61) because each candidate's base is derived from
 * them, as in tools/rankings.mjs. Classification uses the authoring bands the
 * old tool used, because they are what the six published classifications obey.
 *
 * Every ordering is precomputed here and frozen into a lookup table; the
 * browser does no matching arithmetic (`08 § 5`).
 *
 * NOT PRODUCTION. Adopting it means replacing RANKINGS via tools/rankings.mjs.
 */

import { CANDIDATES, TUNABLE } from '../../assets/data/product-demo.js';

/* AUTHORING BANDS, as in tools/rankings.mjs. NOT the published BANDS (72/52/32):
   the data module's own candidates ship at 78 = Good and 74 = Good, which the
   published thresholds would call Strong. That disagreement is a finding for
   the product source to settle (docs/phase-4.md § 1 rule: the source wins), and
   until it is settled the fixture reproduces the classifications the six
   candidates already carry. A threshold is never displayed. */
const AUTHORING_BANDS = [[80, 'strong'], [70, 'good'], [55, 'potential'], [0, 'possible']];

/** Authored weight per tier index: bonus · preferred · required · critical. */
export const TIER_WEIGHT = [2, 5, 9, 18];

/** What a PARTIAL is worth, per tier. Steps down as the tier steps up. */
export const PARTIAL_FACTOR = [0.75, 0.5, 0.4, 0.2];

const CRITICAL = 3;

function state(candidate, skill) {
  if (candidate.skills.covered.includes(skill)) return 'covered';
  if (candidate.skills.partial.some((p) => p.name === skill)) return 'partial';
  return 'missing';
}

function contribution(candidate, combo) {
  return TUNABLE.reduce((sum, t, i) => {
    const s = state(candidate, t.skill);
    const w = TIER_WEIGHT[combo[i]];
    if (s === 'covered') return sum + w;
    if (s === 'partial') return sum + w * PARTIAL_FACTOR[combo[i]];
    return sum;
  }, 0);
}

const DEFAULT_COMBO = TUNABLE.map((t) => t.default);
const BASES = new Map(CANDIDATES.map((c) => [c.id, c.score - contribution(c, DEFAULT_COMBO)]));

function classify(score) {
  return AUTHORING_BANDS.find(([floor]) => score >= floor)[1];
}

/** The skill (if any) whose CRITICAL tier gates this candidate. */
function gatedBy(candidate, combo) {
  const hit = TUNABLE.find((t, i) => combo[i] === CRITICAL && state(candidate, t.skill) === 'missing');
  return hit ? hit.skill : null;
}

/**
 * One ordering. Each entry is [id, score, classification] for a scored
 * candidate, or [id, null, 'gated', skill] for one the gate dropped. Gated
 * rows sort last, in default order.
 */
export function rank(combo) {
  const scored = [];
  const gated = [];
  CANDIDATES.forEach((c) => {
    const g = gatedBy(c, combo);
    if (g) { gated.push([c.id, null, 'gated', g]); return; }
    const score = Math.min(100, Math.max(0, Math.round(BASES.get(c.id) + contribution(c, combo))));
    scored.push([c.id, score, classify(score)]);
  });
  scored.sort((a, b) => b[1] - a[1]);
  return [...scored, ...gated];
}

export const RANKINGS_PROPOSED = {};
for (let p = 0; p <= 3; p += 1) {
  for (let k = 0; k <= 3; k += 1) {
    for (let f = 0; f <= 3; f += 1) {
      RANKINGS_PROPOSED[`${p}-${k}-${f}`] = rank([p, k, f]);
    }
  }
}

/** The browser module the build writes. A lookup table and nothing else. */
export function browserModule() {
  return `/* GENERATED by prototypes/build.mjs from prototypes/lib/rankings-proposed.mjs.
   A precomputed lookup table: sixty-four orderings, no arithmetic. PROPOSED, not
   production — see the authoring file for the model and the reasons. */
export const RANKINGS_PROPOSED = ${JSON.stringify(RANKINGS_PROPOSED)};
`;
}
